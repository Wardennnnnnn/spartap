'use strict';
const {test} = require('node:test');
const assert = require('node:assert/strict');
const {createApplication} = require('../server');
const D = require('../src/domain');
const {MemoryStore} = require('../src/store');
const {request} = require('./helpers/request');
test('scanner registration, replacement, limited access and revocation', async t => {
 const instance = createApplication(new MemoryStore(D.baseDb({demo:true,password:'SafeTapDemo123!'})), {demo:true});
 t.after(() => instance.close());
 const req = (path, cookie, body, csrf) => request(instance.app, {path:'/api'+path, method:body ? 'POST':'GET', headers:{'content-type':'application/json',cookie:cookie || '', 'x-csrf-token':csrf || ''},body});
 const cookie = r => [r.headers['set-cookie']].flat()[0].split(';')[0];
 const data = r => typeof r.body === 'string' ? JSON.parse(r.body) : r.body;
 const login = await req('/login', '', {username:'admin',password:'SafeTapDemo123!'});
 const session = cookie(login);
 const csrf = data(login).csrf;
 assert.equal((await req('/scanner')).status,401);
 assert.equal((await req('/scanner/register',session,{})).status,403);
 const first = await req('/scanner/register',session,{},csrf);
 const phone = cookie(first);
 const access = await req('/scanner',phone);
 assert.equal(access.status,200);
 assert.equal((await req('/state',phone)).status,401);
 assert.equal((await req('/scanner/checkin',phone,{method:'qr',credential:'invalid',eventId:'none',submissionId:'test-submission'},data(access).csrf)).status,409);
 const second = await req('/scanner/register',session,{},csrf);
 assert.equal((await req('/scanner',phone)).status,401);
 const replacement = cookie(second);
 assert.equal((await req('/scanner',replacement)).status,200);
 assert.equal((await req('/scanner/revoke',session,{},csrf)).status,200);
 assert.equal((await req('/scanner',replacement)).status,401);
});
