'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {createApplication}=require('../server');
const {MemoryStore}=require('../src/store');
const D=require('../src/domain');
const {request}=require('./helpers/request');
test('presentation reset is admin/CSRF protected, backs up cleared data and retains directory/accounts',async t=>{
 const store=new MemoryStore(D.baseDb({demo:true,password:'SafeTapDemo123!'}));
 const instance=createApplication(store,{demo:true});t.after(()=>instance.close());
 const req=async(path,body,cookie='',csrf='')=>{
  const r=await request(instance.app,{path:'/api/'+path,method:body?'POST':'GET',headers:{cookie,'x-csrf-token':csrf},body});
  return {...r,data:JSON.parse(r.body)};
 };
 const login=await req('login',{username:'admin',password:'SafeTapDemo123!'});
 const cookie=[login.headers['set-cookie']].flat()[0].split(';')[0],csrf=login.data.csrf;
 assert.equal((await req('scanner/devices')).status,401);
 const registered=await req('scanner/register',{},cookie,csrf);
 const deviceCookie=[registered.headers['set-cookie']].flat()[0].split(';')[0];
 const listed=await req('scanner/devices',undefined,cookie);
 assert.equal(listed.data.devices.length,1);assert.ok(!JSON.stringify(listed.data).includes('tokenHash'));
 const user=store.db.users[0];
 await instance.app.locals.schoolAuthRepository(s=>{s.links['staff@g.batstate-u.edu.ph']={userId:user.id};});
 await store.transact(db=>D.startEvent(db,user,{name:'Presentation test',type:'drill',area:'Assembly point'}));
 const before=await store.read();
 assert.equal((await req('presentation/reset',{confirm:'RESET PRESENTATION'})).status,401);
 assert.equal((await req('presentation/reset',{confirm:'RESET PRESENTATION'},cookie)).status,403);
 assert.equal((await req('presentation/reset',{confirm:'wrong'},cookie,csrf)).status,400);
 assert.equal((await store.read()).events.length,1);
 const reset=await req('presentation/reset',{confirm:'RESET PRESENTATION'},cookie,csrf);
 assert.equal(reset.status,200);assert.equal(reset.data.counts.events,1);assert.equal(reset.data.counts.devices,1);assert.equal(reset.data.counts.emails,1);
 const after=await store.read();
 for(const table of ['users','students','blocks','rooms'])assert.deepEqual(after[table],before[table]);
 for(const table of ['events','classes','attendance','participants','checkins','submissions','audit'])assert.equal(after[table].length,0);
 assert.equal(store.presentationBackups[0].id,reset.data.backupId);assert.equal(store.presentationBackups[0].history.events.length,1);
 assert.equal((await req('scanner',undefined,deviceCookie)).status,401);
 assert.equal((await req('auth/links',undefined,cookie)).data.links.length,0);
 assert.equal((await req('scanner/devices',undefined,cookie)).data.devices.length,0);
});
